"""Rebuild dashboard_data.js (station lists, thresholds and historical statistics
that index.html loads) from the historical dataset and the config in
scripts/nops_psa_conditions_update.py.

Run from the repo root:  python scripts/build_dashboard.py
Re-run after changing thresholds, stations, or the historical CSV.
"""
import json, re, pathlib
import numpy as np
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parents[1]
src = (ROOT / "scripts" / "nops_psa_conditions_update.py").read_text()
cfg_src = src.split("# =============================================================================\ndef fems_csv")[0]
cfg_src = re.sub(r"^(import|from) .*$", "", cfg_src, flags=re.M)
ns = {"pd": pd}
exec(cfg_src, ns)
CFG = {"ST": ns["PSA_STATIONS"],
       "TH": {p: {v: [op, val] for v, (op, val) in t.items()} for p, t in ns["THRESHOLDS"].items()},
       "HR": ns["HIST_LGD_RATE"]}

c = pd.read_csv(ROOT / "data" / "NOPs_Large_Fire_Growth_Days_2012_2026_SIG_Weather.csv")
V = {v: (1 if op == ">=" else -1) for v, (op, _) in ns["THRESHOLDS"]["NC01"].items() if not v.startswith("_")}
d = pd.to_datetime(c.DateText, format="mixed")
c["month"], c["date"] = d.dt.month, d.dt.strftime("%Y-%m-%d")
s = 0
for v, sg in V.items():
    t = c.PSANationa.map(lambda p: ns["THRESHOLDS"][p][v][1])
    s = s + ((c[v] >= t) if sg > 0 else (c[v] <= t)).astype(int)
c["S"] = s
LV = ["Low", "Moderate", "High", "Very High"]
TH = ns["THRESHOLDS"]
c["G"] = ((c.ERC < c.PSANationa.map(lambda p: TH[p]["_gate_ERC"][1])) |
          (c.F100 > c.PSANationa.map(lambda p: TH[p]["_gate_F100"][1]))).astype(int)   # fuel gate
c["L"] = pd.cut(c.S, [-1, 1, 3, 5, 8], labels=LV).astype(str).where(c.G == 0, "Low")

def q(x):
    # min, 10th, 25th, median, 75th, 90th, max
    return [round(float(x.quantile(k)), 1) for k in (0, .1, .25, .5, .75, .9, 1)]

HIST = {}
for p, g in list(c.groupby("PSANationa")) + [("ALL", c)]:
    lg = g[g.LargeGrowthDayFlag == 1]
    o = {"n": int(len(g)), "nlgd": int(len(lg)), "base": round(float(g.LargeGrowthDayFlag.mean() * 100), 1)}
    o["levels"] = [{"level": l, "days": int((g.L == l).sum()),
                    "lgd": int(g[g.L == l].LargeGrowthDayFlag.sum()),
                    "rate": round(float(g[g.L == l].LargeGrowthDayFlag.mean() * 100), 1) if (g.L == l).sum() else None}
                   for l in LV]
    o["vars"] = {v: {"lgd": q(lg[v].dropna()), "oth": q(g[g.LargeGrowthDayFlag == 0][v].dropna())}
                 for v in list(V) + ["Temp", "RH", "Wind"]}
    m = lg.groupby("month").size()
    o["months"] = [int(m.get(i, 0)) for i in range(1, 13)]
    o["top"] = [{"date": r.date, "fire": str(r.FireName).title(), "psa": r.PSANationa, "acres": int(r.Fire_Size),
                 "S": int(r.S), "L": str(r.L), "G": int(r.G)} for r in lg.sort_values("Fire_Size", ascending=False).head(10).itertuples()]
    HIST[p] = o

# ERC and 100-hr FM on each PSA's large growth days (sorted), for "lower than on k of n" comparisons
LGDF = {p: {v: sorted(round(float(x), 1) for x in g[g.LargeGrowthDayFlag == 1][v].dropna()) for v in ("ERC", "F100")}
        for p, g in c.groupby("PSANationa")}
js = ("// Generated by scripts/build_dashboard.py - do not edit by hand.\n"
      "const CFG = " + json.dumps(CFG, separators=(",", ":")) + ";\n"
      "const HIST = " + json.dumps(HIST, separators=(",", ":")) + ";\n"
      "const LGDF = " + json.dumps(LGDF, separators=(",", ":")) + ";\n")
(ROOT / "dashboard_data.js").write_text(js)
print("Wrote dashboard_data.js", len(js), "bytes")

# ---- Row-level history for the explorer tabs (data/history_rows.json) ----
# Growth % from acres (the day's growth over the fire's size the day before); the supplied
# GrowthPercent column is blank or 0 on many 2020-2026 rows.
_prior = c.Fire_Size_Cumulative - c.Fire_Size
c["GrowthCalc"] = (c.Fire_Size / _prior.where(_prior > 0) * 100).clip(upper=99999)
F = [("date", None), ("fire", None), ("psa", "PSANationa"), ("acres", "Fire_Size"), ("growth", "GrowthCalc"),
     ("lgd", "LargeGrowthDayFlag"), ("Temp", "Temp"), ("MaxT", "MaxT"), ("RH", "RH"), ("MxRH", "MxRH"),
     ("Rain", "Rain"), ("RnDr", "RnDr"), ("Wind", "Wind"), ("WDir", "WDIR_deg"), ("GSpd", "GSpd"), ("GDir", "GDir"),
     ("VPDM", "VPDM"), ("VPDA", "VPDA"), ("FFWI", "FFWI"), ("SC", "SC"), ("ERC", "ERC"), ("BI", "BI"), ("IC", "IC"),
     ("F100", "F100"), ("F1000", "F1000"), ("L0", "Lightning_Day"), ("L3", "Lightning_Prior3d"),
     ("L7", "Lightning_Prior7d"), ("LC", "Lightning_Cluster_Flag"), ("WE", "Large_Wind_Event_Flag"),
     ("WT", "Wind_Event_Threshold_mph"), ("Starts", "Large_Fire_Starts_PSA_Day"), ("Score", None), ("G", None)]
rows = []
for i, r in c.iterrows():
    out = []
    for k, col in F:
        if k == "date": v = r.date
        elif k == "fire": v = str(r.FireName).title()
        elif k == "psa": v = r.PSANationa
        elif k == "Score": v = int(r.S)
        elif k == "G": v = int(r.G)
        else:
            v = r[col]
            if pd.isna(v): v = None
            elif k in ("acres", "growth", "lgd", "L0", "L3", "L7", "LC", "WE", "Starts", "RnDr"): v = int(round(float(v)))
            elif k in ("WDir", "GDir", "VPDM", "VPDA"): v = int(round(float(v)))
            else: v = round(float(v), 1)
        out.append(v)
    rows.append(out)
hist_rows = {"fields": [k for k, _ in F], "rows": sorted(rows, key=lambda x: x[0])}
(ROOT / "data" / "history_rows.json").write_text(json.dumps(hist_rows, separators=(",", ":")))
# Same data as a script, so the dashboard's history tabs also work when index.html is opened as a local file
(ROOT / "data" / "history_rows.js").write_text("window.HISTORY_ROWS = " + json.dumps(hist_rows, separators=(",", ":")) + ";\n")
print("Wrote data/history_rows.json", len(rows), "rows")
